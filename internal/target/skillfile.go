package target

import (
	"bytes"
	"fmt"
	"strconv"
)

// skillFiles renders a skill into a harness's directory: the SKILL.md, a
// gitignore so the generated directory ignores itself, and the assets in the
// layout they were authored in.
//
// Only the frontmatter differs between harnesses, so only the frontmatter is
// passed in. The body is written here for all of them, which is what makes a
// skill delivered to one tool provably the same text as the skill delivered to
// another rather than two copies that drift.
func skillFiles(dir string, s Skill, frontmatter func(*bytes.Buffer)) []File {
	files := []File{
		{Path: dir + "/SKILL.md", Body: renderSkillFile(s, frontmatter)},
		{Path: dir + "/.gitignore", Body: []byte(generatedGitignore)},
	}
	for _, a := range s.Assets {
		files = append(files, File{Path: dir + "/" + a.Path, Body: a.Body})
	}
	return files
}

func renderSkillFile(s Skill, frontmatter func(*bytes.Buffer)) []byte {
	var b bytes.Buffer

	b.WriteString("---\n")
	fmt.Fprintf(&b, "# Generated by Quartermaster. Do not edit; edit the source document instead.\n")
	fmt.Fprintf(&b, "# source: %s  bundle: %s", s.ID, s.Digest)
	if s.Commit != "" {
		fmt.Fprintf(&b, "  commit: %s", s.Commit)
	}
	b.WriteByte('\n')

	// Every harness identifies a skill by name and decides whether to load it
	// from the description, so both are always written.
	fmt.Fprintf(&b, "name: %s\n", s.Name)
	if s.Description != "" {
		fmt.Fprintf(&b, "description: %s\n", strconv.Quote(s.Description))
	}
	frontmatter(&b)
	b.WriteString("---\n\n")

	prose := bytes.TrimLeft(s.Prose, "\n")
	b.Write(prose)
	if !bytes.HasSuffix(prose, []byte("\n")) {
		b.WriteByte('\n')
	}
	return b.Bytes()
}
