package target

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"
)

// ClaudeRulesDir is where the claude target writes rules, under a qm/
// subdirectory so there is never ambiguity about which files are generated and
// safe to delete.
const ClaudeRulesDir = ".claude/rules/qm"

// ClaudeSkillsDir is where the harness looks for skills. Skills cannot nest
// under a qm/ subdirectory the way rules do, because the harness reads the
// directory name as the skill's identity: .claude/skills/gcp-expert is invoked
// as /gcp-expert. That rules out a shared prefix or a containing folder, so a
// generated skill sits directly beside a hand-written one.
//
// Since no single gitignore pattern can then separate the two, each generated
// skill directory carries its own .gitignore instead. The directory ignores
// itself, nothing has to be kept in step at the repository root, and removing
// the skill removes the rule that ignored it.
const ClaudeSkillsDir = ".claude/skills"

// generatedGitignore makes a generated directory ignore itself, including this
// file.
const generatedGitignore = "# Generated by Quartermaster; regenerated by `qm sync`.\n*\n"

// claude renders Claude Code rule files.
//
// A scoped rule declares its globs in a paths frontmatter field, which the
// harness watches; an unscoped rule omits paths and loads every session. The
// body is the document's prose verbatim: size is controlled by keeping rulesets
// tight, not by extracting a single imperative line from each document, which
// would put a second statement of the same claim in the store with nothing
// checking that the two agree.
type claude struct{}

func (claude) Name() string { return "claude" }

// IgnorePaths covers the rules directory, which Quartermaster owns whole.
// Skills are not listed: they sit among hand-written ones and ignore themselves.
func (claude) IgnorePaths() []string { return []string{ClaudeRulesDir + "/"} }

func (claude) Render(in Input) (Output, error) {
	files := make([]File, 0, len(in.Docs))
	for _, d := range in.Docs {
		files = append(files, File{
			Path: fmt.Sprintf("%s/%s.md", ClaudeRulesDir, d.ID),
			Body: renderClaudeRule(d),
		})
	}

	for _, s := range in.Skills {
		dir := fmt.Sprintf("%s/%s", ClaudeSkillsDir, s.Name)
		files = append(files,
			File{Path: dir + "/SKILL.md", Body: renderClaudeSkill(s)},
			File{Path: dir + "/.gitignore", Body: []byte(generatedGitignore)},
		)
		// Assets keep their layout, so a skill that says "see references/foo.md"
		// is telling the truth once materialized.
		for _, a := range s.Assets {
			files = append(files, File{Path: dir + "/" + a.Path, Body: a.Body})
		}
	}

	return Output{Files: files}, nil
}

// renderClaudeSkill writes the harness's own skill frontmatter. A skill is
// discovered by its description, so that field carries the whole decision of
// whether to load it.
func renderClaudeSkill(s Skill) []byte {
	var b bytes.Buffer

	b.WriteString("---\n")
	fmt.Fprintf(&b, "# Generated by Quartermaster. Do not edit; edit the source document instead.\n")
	fmt.Fprintf(&b, "# source: %s  bundle: %s", s.ID, s.Digest)
	if s.Commit != "" {
		fmt.Fprintf(&b, "  commit: %s", s.Commit)
	}
	b.WriteByte('\n')

	fmt.Fprintf(&b, "name: %s\n", s.Name)
	if s.Description != "" {
		fmt.Fprintf(&b, "description: %s\n", strconv.Quote(s.Description))
	}
	if len(s.AllowedTools) > 0 {
		fmt.Fprintf(&b, "allowed-tools: %s\n", strings.Join(s.AllowedTools, ", "))
	}
	b.WriteString("---\n\n")

	prose := bytes.TrimLeft(s.Prose, "\n")
	b.Write(prose)
	if !bytes.HasSuffix(prose, []byte("\n")) {
		b.WriteByte('\n')
	}
	return b.Bytes()
}

func renderClaudeRule(d Doc) []byte {
	var b bytes.Buffer

	b.WriteString("---\n")
	fmt.Fprintf(&b, "# Generated by Quartermaster. Do not edit; edit the source document instead.\n")
	fmt.Fprintf(&b, "# source: %s  bundle: %s", d.ID, d.Digest)
	if d.Commit != "" {
		fmt.Fprintf(&b, "  commit: %s", d.Commit)
	}
	b.WriteByte('\n')

	if d.Description != "" {
		fmt.Fprintf(&b, "description: %s\n", strconv.Quote(d.Description))
	}
	if len(d.Scope) > 0 {
		b.WriteString("paths:\n")
		for _, g := range d.Scope {
			fmt.Fprintf(&b, "  - %s\n", strconv.Quote(g))
		}
	}
	b.WriteString("---\n\n")

	prose := bytes.TrimLeft(d.Prose, "\n")
	b.Write(prose)
	if !bytes.HasSuffix(prose, []byte("\n")) {
		b.WriteByte('\n')
	}

	return b.Bytes()
}
