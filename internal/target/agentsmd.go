package target

import (
	"fmt"
	"strings"
)

// AgentsMDFile is the committed file the agents-md target manages a block in.
const AgentsMDFile = "AGENTS.md"

// AgentsMDMarker names the managed region inside AGENTS.md.
const AgentsMDMarker = "QUARTERMASTER"

// agentsMD renders a managed block in AGENTS.md.
//
// AGENTS.md is committed, so the block holds a pointer rather than inlined
// rules: the bundle it draws from, the rulesets applied, and a listing of the
// rules with their scope described in prose. The full rule text lives in the
// gitignored harness directories and the retrievable tree. A pointer is stable
// per digest, so it does not conflict on every merge the way inlined generated
// content would.
type agentsMD struct{}

func (agentsMD) Name() string { return "agents-md" }

// IgnorePaths returns nil: the agents-md block lives in a committed file.
func (agentsMD) IgnorePaths() []string { return nil }

func (agentsMD) Render(in Input) (Output, error) {
	var b strings.Builder

	b.WriteString("Generated by Quartermaster. Do not edit inside these markers; run `qm sync`.\n\n")

	for _, bd := range in.Bundles {
		fmt.Fprintf(&b, "Knowledge bundle `%s`", bd.Digest)
		if len(bd.Rulesets) > 0 {
			fmt.Fprintf(&b, " — rulesets: %s", strings.Join(bd.Rulesets, ", "))
		}
		b.WriteString("\n")
	}
	b.WriteString("\nMaterialized rules live under the harness rule directories; retrievable docs under `.quartermaster/knowledge/`.\n")

	var resident, scoped []Doc
	for _, d := range in.Docs {
		if len(d.Scope) == 0 {
			resident = append(resident, d)
		} else {
			scoped = append(scoped, d)
		}
	}

	if len(resident) > 0 {
		b.WriteString("\nResident rules (apply every session):\n")
		for _, d := range resident {
			fmt.Fprintf(&b, "- `%s` — %s\n", d.ID, d.Description)
		}
	}
	if len(scoped) > 0 {
		b.WriteString("\nScoped rules:\n")
		for _, d := range scoped {
			fmt.Fprintf(&b, "- `%s` (%s) — %s\n", d.ID, strings.Join(d.Scope, ", "), d.Description)
		}
	}

	return Output{Blocks: []Block{{
		Path:   AgentsMDFile,
		Marker: AgentsMDMarker,
		Body:   b.String(),
	}}}, nil
}
