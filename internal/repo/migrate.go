package repo

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/mberwanger/quartermaster/internal/manifest"
	"github.com/mberwanger/quartermaster/internal/state"
)

// Migrate moves a repository from the names an earlier release used to the
// current ones, and returns a line for each thing it changed. A repository with
// nothing legacy in it comes back untouched with no lines.
//
// The manifest is renamed in place, so the author sees one rename to commit.
// The state is carried across so the next sync still prunes the files the last
// one wrote, with the knowledge paths rewritten to where they now live. The old
// directory itself is removed rather than moved: everything in it is
// regenerated by the sync that follows, and the gitignore entry that covered it
// is retargeted so the ignore list does not keep naming a directory that no
// longer exists.
func Migrate(dir string) ([]string, error) {
	var done []string

	legacy := filepath.Join(dir, manifest.LegacyFileName)
	current := filepath.Join(dir, manifest.FileName)
	if exists(legacy) && !exists(current) {
		if err := os.Rename(legacy, current); err != nil {
			return nil, err
		}
		done = append(done, fmt.Sprintf("renamed %s to %s", manifest.LegacyFileName, manifest.FileName))
	}

	legacyDir := filepath.Join(dir, state.LegacyDir)
	if exists(legacyDir) {
		if err := carryState(dir); err != nil {
			return nil, err
		}
		if err := os.RemoveAll(legacyDir); err != nil {
			return nil, err
		}
		done = append(done, fmt.Sprintf("removed %s/; the sync that follows regenerates it under %s/", state.LegacyDir, state.Dir))
	}

	retargeted, err := retargetGitignore(dir)
	if err != nil {
		return nil, err
	}
	if retargeted {
		done = append(done, fmt.Sprintf(".gitignore now covers /%s/ instead of /%s/", state.Dir, state.LegacyDir))
	}

	return done, nil
}

// carryState copies the last sync's record out of the legacy directory, so the
// files it produced are still pruned when this sync no longer produces them. A
// record already under the current directory is the newer one and wins.
func carryState(dir string) error {
	if exists(filepath.Join(dir, state.Dir)) {
		return nil
	}
	old, err := state.LoadFrom(filepath.Join(dir, state.LegacyDir))
	if err != nil {
		return err
	}
	for i, f := range old.Files {
		if rest, ok := strings.CutPrefix(f, state.LegacyDir+"/"); ok {
			old.Files[i] = state.Dir + "/" + rest
		}
	}
	return state.Save(dir, old)
}

// retargetGitignore rewrites the entry that ignored the legacy directory to
// ignore the current one, in place, and reports whether it changed anything.
func retargetGitignore(dir string) (bool, error) {
	path := filepath.Join(dir, ".gitignore")
	raw, err := os.ReadFile(path) //nolint:gosec // dir is a CLI flag
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}

	oldEntry, newEntry := "/"+state.LegacyDir+"/", "/"+state.Dir+"/"
	var out bytes.Buffer
	var changed, present bool
	sc := bufio.NewScanner(bytes.NewReader(raw))
	for sc.Scan() {
		line := sc.Text()
		if strings.TrimSpace(line) == newEntry {
			present = true
		}
	}
	sc = bufio.NewScanner(bytes.NewReader(raw))
	for sc.Scan() {
		line := sc.Text()
		if strings.TrimSpace(line) == oldEntry {
			if present {
				changed = true
				continue // already covered; drop the stale entry
			}
			line, changed, present = newEntry, true, true
		}
		out.WriteString(line)
		out.WriteByte('\n')
	}
	if !changed {
		return false, nil
	}
	return true, os.WriteFile(path, out.Bytes(), 0o644) //nolint:gosec // .gitignore is committed and world-readable
}

func exists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}
